// چت (نه در systemPrompt مخفی)، ثابت و بدون تماس شبکه. برای ثبت‌نام سریع، کل سوالات لازم
// (۲ تا برای store-setup) این‌جا یکجا نشان داده می‌شوند تا فروشنده کلیت کار را از همون اول
// ببیند؛ cluster/category فقط برای انتخاب مثالِ مرتبط با نوع کسب‌وکار استفاده می‌شود.
// systemPrompt (buildGuidePrompt) جدا برای مدل ارسال می‌شود و هرگز مستقیم نشان داده نمی‌شود.
export function buildGuideOpeningMessage(
  context: 'store-setup' | 'product',
  opts?: { name?: string | null; category?: string | null; businessType?: 'PRODUCT_SALES' | 'APPOINTMENT_BOOKING' },
): string {
  const greetingTarget = opts?.name ? `فروشگاه «${opts.name}»` : 'فروشگاهت'
  const cluster = resolveCluster(opts?.category, opts?.businessType)
  const voiceLine =
    'می‌تونی به‌جای تایپ، با صدا هم توضیح بدی (دکمه‌ی میکروفون پایین چت) — یکجا همه رو با صدا بگو یا تکی‌تکی تایپ کن، هرجور راحتی.'

  if (context === 'store-setup') {
    const q1Example = (opts?.category && STORE_Q1_EXAMPLE_BY_CATEGORY[opts.category]) || DEFAULT_STORE_Q1_EXAMPLE
    return `سلام 👋 بیا با هم ${greetingTarget} رو سریع معرفی کنیم — فقط همین ۲ سوال کوتاه کافیه برای شروع ثبت‌نام، بقیه‌ی تنظیمات رو بعداً از پروفایل فروشگاه کامل می‌کنی. ${voiceLine}

۱. فروشگاهت دقیقاً چی می‌فروشه؟
   - ضعیف: «لباس می‌فروشم»
   - خوب: «${q1Example}»

۲. چه چیزی شما رو از رقبا متفاوت می‌کنه؟
   - ضعیف: «کیفیت بالا داریم»
   - خوب: «دو سال گارانتی، تولیدکننده مستقیم بدون واسطه، ارسال رایگان بالای یه مبلغ خاص»`
  }

  const q1 = PRODUCT_Q1_BY_CLUSTER[cluster] ?? DEFAULT_PRODUCT_Q1
  return `سلام 👋 بیا با هم چندتا سوال کوتاه درباره‌ی این محصول مرور کنیم تا بتونم یه توضیح دقیق و قانع‌کننده براش بنویسم. ${voiceLine}

${q1}`
}

